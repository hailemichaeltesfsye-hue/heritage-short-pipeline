@app.get("/api/storyboard")
def get_storyboard() -> Dict[str, Any]:
    """Read storyboard.json and validate against schema."""
    is_valid, errors, data = validate_storyboard(STORYBOARD_PATH, SCHEMA_PATH)
    return {
        "is_valid": is_valid,
        "errors": errors,
        "storyboard": data,
    }


@app.put("/api/storyboard/shot/{shot_id}")
def update_shot(shot_id: str, request: ShotUpdateRequest) -> Dict[str, Any]:
    """Update a single shot's parameters safely and invalidate its cache."""
    if not STORYBOARD_PATH.exists():
        raise HTTPException(status_code=404, detail="storyboard.json not found")

    with open(STORYBOARD_PATH, "r", encoding="utf-8") as f:
        storyboard = json.load(f)

    target_idx = None
    target_shot = None
    for i, s in enumerate(storyboard.get("shots", [])):
        if s.get("shot_id") == shot_id:
            target_idx = i
            target_shot = dict(s)
            break

    if target_idx is None or target_shot is None:
        raise HTTPException(status_code=404, detail=f"Shot {shot_id} not found in storyboard")

    # Apply updates
    update_data = request.model_dump(exclude_unset=True)
    for k, v in update_data.items():
        if v is not None:
            target_shot[k] = v

    storyboard["shots"][target_idx] = target_shot

    # Validate updated storyboard against schema
    import jsonschema
    with open(SCHEMA_PATH, "r", encoding="utf-8") as f:
        schema = json.load(f)

    validator = jsonschema.Draft202012Validator(schema)
    validation_errors = [f"[{e.json_path}]: {e.message}" for e in validator.iter_errors(storyboard)]
    if validation_errors:
        raise HTTPException(status_code=422, detail={"errors": validation_errors})

    # Save to disk
    with open(STORYBOARD_PATH, "w", encoding="utf-8") as f:
        json.dump(storyboard, f, indent=2, ensure_ascii=False)

    # Invalidate cache for this single shot
    invalidate_shot(shot_id)
    new_hash = compute_shot_hash(target_shot, storyboard.get("style_block", {}))

    log_run(
        agent="StoryDirectorAgent",
        stage="shot_update",
        shot_id=shot_id,
        provider="local",
        model="storyboard-editor",
        parameters=update_data,
        status="success",
    )

    return {
        "success": True,
        "shot_id": shot_id,
        "new_hash": new_hash,
        "shot": target_shot,
    }


@app.post("/api/pipeline/run")
def run_pipeline_stage(req: PipelineRunRequest) -> Dict[str, Any]:
    """Execute pipeline stage (synchronous or single-shot)."""
    with open(STORYBOARD_PATH, "r", encoding="utf-8") as f:
        storyboard_data = json.load(f)

    stage = req.stage.lower()

    if stage in ("all", "graph"):
        from agents.graph import create_pipeline_graph
        graph = create_pipeline_graph()
        initial_state = {
            "storyboard_path": str(STORYBOARD_PATH),
            "storyboard_data": storyboard_data,
            "dry_run": req.dry_run,
            "hitl": req.hitl,
            "target_shot_id": req.shot_id,
            "force": req.force,
            "stage": stage,
            "trace_id": f"api-{int(time.time())}",
            "is_valid_schema": False,
            "safety_passed": False,
            "shot_hashes": {},
            "keyframes": {},
            "audio_files": {},
            "shots_video": {},
            "score_path": None,
            "radio_cut_path": None,
            "final_16x9_path": None,
            "final_9x16_path": None,
            "errors": [],
            "retry_counts": {},
            "step_status": {},
            "hitl_paused": False,
        }
        res = graph.invoke(initial_state)
        return {
            "status": "success" if not res.get("errors") else "error",
            "stage": stage,
            "errors": res.get("errors", []),
            "final_16x9": res.get("final_16x9_path"),
            "final_9x16": res.get("final_9x16_path"),
        }

    if stage == "keyframes":
        from pipeline.keyframes import generate_all_keyframes, generate_shot_keyframe
        if req.shot_id:
            target = next((s for s in storyboard_data["shots"] if s["shot_id"] == req.shot_id), None)
            if not target:
                raise HTTPException(status_code=404, detail=f"Shot {req.shot_id} not found")
            success, path, _ = generate_shot_keyframe(
                target, storyboard_data.get("style_block", {}), dry_run=req.dry_run, force=req.force
            )
            return {"status": "success" if success else "failed", "shot_id": req.shot_id, "keyframe": str(path)}
        res_map = generate_all_keyframes(storyboard_data, dry_run=req.dry_run, force=req.force)
        return {"status": "success", "count": len(res_map)}

    if stage in ("narration", "voice"):
        from pipeline.narration import generate_shot_narration
        shots_to_run = storyboard_data.get("shots", [])
        if req.shot_id:
            shots_to_run = [s for s in shots_to_run if s["shot_id"] == req.shot_id]
        results = {}
        for s in shots_to_run:
            succ, p, mod, _ = generate_shot_narration(s, dry_run=req.dry_run)
            results[s["shot_id"]] = str(p)
        return {"status": "success", "narration_files": results}

    if stage == "music":
        from pipeline.music import prepare_score
        dur = float(storyboard_data.get("total_duration_sec", 74.0))
        score_path = prepare_score(dur)
        return {"status": "success", "score": str(score_path)}

    if stage in ("assemble", "radio-cut"):
        from pipeline.assemble import assemble_full_dual_aspect_pipeline
        f16, f9 = assemble_full_dual_aspect_pipeline(storyboard_data, dry_run=req.dry_run)
        return {"status": "success", "final_16x9": str(f16), "final_9x16": str(f9)}

    raise HTTPException(status_code=400, detail=f"Unsupported stage '{stage}'")


@app.post("/api/pipeline/approve")
def approve_hitl() -> Dict[str, Any]:
    """Advance HITL checkpoint approval."""
    _hitl_state["paused"] = False
    _hitl_state["approved_at"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    return {
        "status": "approved",
        "approved_at": _hitl_state["approved_at"],
        "message": "Human-In-The-Loop checkpoint approved.",
    }


@app.get("/api/metrics")
def get_metrics() -> Dict[str, Any]:
    """Parse runs.jsonl live for real telemetry, costs, and breakdown."""
    base_metrics = get_pipeline_metrics(RUNS_LOG_PATH)

    recent_runs: List[Dict[str, Any]] = []
    model_breakdown: Dict[str, int] = {}
    stage_breakdown: Dict[str, Dict[str, Any]] = {}

    if RUNS_LOG_PATH.exists():
        with open(RUNS_LOG_PATH, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    entry = json.loads(line)
                    recent_runs.append(entry)

                    # Model counts
                    model = entry.get("model", "unknown")
                    model_breakdown[model] = model_breakdown.get(model, 0) + 1

                    # Stage stats
                    stage = entry.get("stage", "general")
                    if stage not in stage_breakdown:
                        stage_breakdown[stage] = {"count": 0, "total_latency_ms": 0.0, "total_cost_usd": 0.0}
                    stage_breakdown[stage]["count"] += 1
                    stage_breakdown[stage]["total_latency_ms"] += entry.get("latency_ms", 0.0)
                    stage_breakdown[stage]["total_cost_usd"] += entry.get("estimated_cost_usd", 0.0)
                except Exception:
                    continue

    # Keep only the last 30 runs for the table
    recent_runs = recent_runs[-30:][::-1]

    # Inspect Wan 2.2 report if present
    wan_report_path = OUTPUTS_DIR / "clips_raw" / "wan22_generation_report.json"
    gpu_minutes = 0.0
    if wan_report_path.exists():
        try:
            with open(wan_report_path, "r", encoding="utf-8") as f:
                wan_data = json.load(f)
                gpu_minutes = wan_data.get("total_gpu_minutes", 0.0)
        except Exception:
            pass

    return {
        "summary": base_metrics,
        "estimated_gpu_minutes": gpu_minutes,
        "model_breakdown": model_breakdown,
        "stage_breakdown": stage_breakdown,
        "recent_runs": recent_runs,
        "hitl_state": _hitl_state,
    }


@app.get("/api/docs")
def get_docs() -> Dict[str, str]:
    """Read all engineering journals and governance documents directly from root."""
    doc_files = [
        "DESIGN.md",
        "ARCHITECTURE.md",
        "EXPERIMENTS.md",
        "FAILURES.md",
        "COSTS.md",
        "ETHICS.md",
    ]
    docs: Dict[str, str] = {}
    for filename in doc_files:
        p = Path(filename)
        if p.exists():
            docs[p.stem] = p.read_text(encoding="utf-8")
        else:
            docs[p.stem] = f"# {filename}\nFile not found."

    return docs
