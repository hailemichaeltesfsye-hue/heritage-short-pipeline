"""FastAPI REST bridge for the Heritage Short filmmaking pipeline.

Exposes real endpoints for:
- Storyboard inspection and single-shot safe updating
- Live pipeline execution and HITL approval checkpoints
- Real telemetry metrics directly from runs.jsonl
- Engineering markdown journals
- Static media streaming directly from outputs/
"""

from __future__ import annotations

import json
from pathlib import Path
import time
from typing import Any, Dict, List, Optional

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, Field

from pipeline.cache import compute_shot_hash, invalidate_shot
from pipeline.ffmpeg_utils import resolve_ffmpeg_path
from pipeline.logger import get_pipeline_metrics, log_run
from pipeline.script import validate_storyboard

STORYBOARD_PATH = Path("storyboard.json")
SCHEMA_PATH = Path("schema/storyboard.schema.json")
RUNS_LOG_PATH = Path("runs.jsonl")
OUTPUTS_DIR = Path("outputs")
OUTPUTS_DIR.mkdir(parents=True, exist_ok=True)

app = FastAPI(
    title="The Heritage Short AI Filmmaking Pipeline API",
    description="Interactive control plane and showcase bridge for the Amharic short film 'Hulum Neger Lebego New'",
    version="1.0.0",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# Serve media files generated by FFmpeg and AI models
app.mount("/media", StaticFiles(directory=str(OUTPUTS_DIR), html=False, check_dir=False), name="media")

# In-memory tracking for HITL checkpoint state
_hitl_state: Dict[str, Any] = {
    "paused": False,
    "last_checkpoint": None,
    "approved_at": None,
}


class ShotUpdateRequest(BaseModel):
    duration_sec: Optional[float] = Field(None, ge=1.0, le=30.0)
    shot_type: Optional[str] = None
    visual_prompt: Optional[str] = None
    motion_prompt: Optional[str] = None
    narration_am: Optional[str] = None
    subtitle_en: Optional[str] = None
    reason: Optional[str] = None
    seed: Optional[int] = Field(None, ge=0)


class PipelineRunRequest(BaseModel):
    stage: str = Field("all", description="all, keyframes, shots, music, assemble, narration, radio-cut")
    shot_id: Optional[str] = None
    dry_run: bool = True
    force: bool = False
    hitl: bool = False


